# Concatenation (joining strings)
first_name = "Shahiddin"
last_name = "Shaik"
full_name = first_name + " " + last_name
print(full_name)

# Repetition
line = "-"*20
print(line)

star = "*"*20
print(star)

# Membership
text = "I love Python"
print("Python" in text)
print("shahid" in text)
print("Love" in text)
print("love" in text)
print("Shahid" not in text)
