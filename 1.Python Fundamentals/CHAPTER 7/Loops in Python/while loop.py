# while = Keep doing this WHILE condition is True
# count 1 to 5
count =1
while count<=5:
    print(count)
    count+=1    # IMPORTANT! Without this, loop runs forever!

count = 0
while count<=10:
    print(count)
    count+=1
    
count = 1
while count<=3:
    print(f"Iteration: {count}")
    count += 1