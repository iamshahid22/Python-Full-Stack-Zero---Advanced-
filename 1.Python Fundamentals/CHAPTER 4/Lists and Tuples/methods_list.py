numbers = [3,1,2,4,5,6,7,4,2]

print(numbers.count(2)) #counts how many times a number appears 

print(numbers.index(2))  #first position of 2

numbers.sort()
print(numbers) #sorted

numbers.reverse() #reversed
print(numbers)

print(len(numbers)) #length of list 

#built in functions for lists
print(min(numbers))
print(max(numbers))
print(sum(numbers))