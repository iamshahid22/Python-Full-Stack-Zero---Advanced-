#Function = A named block of code you can call anytime.
# ✅ Write code once, use many times (DRY - Don't Repeat Yourself)
# ✅ Organize code into logical chunks
# ✅ Easier to read and understand
# ✅ Easier to debug (fix errors)
# ✅ Can test individual parts
 
 
# DEFINING a function (creating it)
def greet():          # 'def' keyword, function name, brackets, colon
    print("Hello!")   # Indented code inside function
    print("How are you?")

# CALLING a function (using it)
greet()    # Hello! How are you?
greet()    # Hello! How are you? 
greet()    # Hello! How are you? 